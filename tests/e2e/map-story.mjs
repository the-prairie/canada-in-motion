import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,...(process.env.TEST_BROWSER_PATH?{executablePath:process.env.TEST_BROWSER_PATH}:{})});
const base=process.env.TEST_URL||'http://127.0.0.1:4201/';
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],checks=[];
page.on('pageerror',error=>errors.push(error.message));
await page.route('**/api/analysis/status',route=>route.fulfill({json:{available:false}}));
await page.route('**/api/analysis',()=>{throw Error('This journey must not invoke inference');});
const url=patch=>base+'#v1='+encodeURIComponent(JSON.stringify({view:'economy',economy:{section:'trade',tradeDisplay:'map',tradeConnection:'AB-BC',tradeCommodity:'oil',tradeYear:2024,guideStep:'exchange',...patch}}));
const stage=name=>page.getByRole('navigation',{name:'Scenario stages'}).getByRole('button',{name,exact:true});
const stableMap=()=>page.waitForFunction(()=>{const svg=document.querySelector('.gsm-map svg');if(!svg)return false;const rect=svg.getBoundingClientRect(),box=svg.viewBox.baseVal;return Math.abs(rect.width-box.width)<.1&&Math.abs(rect.height-box.height)<.1;});
const noOverflow=()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1);
const inspect=region=>page.locator(`.gsm-endpoint.gsm-${region==='AB'?'seller':'buyer'}`);
const visibleHeading=()=>page.waitForFunction(()=>{const heading=document.querySelector('.gs-stage>h4').getBoundingClientRect(),map=document.querySelector('.gsm-map'),inset=getComputedStyle(map).position==='sticky'?map.getBoundingClientRect().bottom:0;return heading.top>=inset-1&&heading.bottom<innerHeight;});
try{
  await page.goto(url({}));await page.locator('.gsm-map').waitFor();await stableMap();
  await page.locator('.gsm-map').scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>document.querySelector('.gsm-map').classList.contains('is-playing'));
  const path=await page.locator('.gsm-link').getAttribute('d');
  await page.locator('.gsm-map').evaluate(node=>node.dataset.persistenceCheck='retained');
  const initial=await page.locator('.gsm-flow').evaluate(node=>({width:getComputedStyle(node).strokeWidth,speed:getComputedStyle(node).animationDuration}));
  assert.equal(await page.locator('.gsm-flow').evaluate(node=>getComputedStyle(node).animationPlayState),'running');
  const pause=page.getByRole('button',{name:'Pause trade flow',exact:true});
  assert.equal(await pause.evaluate(node=>getComputedStyle(node).color),'rgb(40, 95, 84)');
  await pause.click();assert.equal(await page.locator('.gsm-flow').evaluate(node=>getComputedStyle(node).animationPlayState),'paused');
  await page.getByRole('button',{name:'Play trade flow',exact:true}).click();
  await page.getByLabel('Commodity price change percent',{exact:true}).fill('-10');
  assert.match(await page.locator('.gsm-endpoints').innerText(),/−\$136.2M/);
  assert.equal(await page.locator('.gsm-link').getAttribute('d'),path);
  assert.deepEqual(await page.locator('.gsm-flow').evaluate(node=>({width:getComputedStyle(node).strokeWidth,speed:getComputedStyle(node).animationDuration})),initial);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.getByRole('button',{name:'Flow motion disabled by reduced-motion preference',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Flow motion disabled by reduced-motion preference',exact:true}).isDisabled(),true);
  assert.equal(await page.locator('.gsm-flow').evaluate(node=>getComputedStyle(node).animationName),'none');
  assert.ok(await page.locator('.gsm-link').getAttribute('marker-end'));
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.setViewportSize({width:1440,height:500});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.waitForFunction(()=>!document.querySelector('.gsm-map').classList.contains('is-playing'));
  await page.setViewportSize({width:1440,height:1000});await stableMap();
  await page.locator('.gsm-map').scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>document.querySelector('.gsm-map').classList.contains('is-playing'));
  checks.push('motion plays only in view, supports pause and reduced motion, and never changes speed or path with prices');

  await stage('Provincial economy').click();await page.locator('[data-guide-province="BC"]').waitFor();
  assert.equal(await page.locator('.gsm-map').getAttribute('data-persistence-check'),'retained');
  assert.equal(await page.locator('.gsm-link').getAttribute('d'),path);
  assert.equal(await page.locator('.gsm-flow').count(),0);
  assert.equal(await inspect('AB').locator('strong').innerText(),'No estimate');
  assert.equal(await inspect('BC').locator('strong').innerText(),await page.locator('[data-guide-province="BC"] .gs-result').innerText());
  await inspect('BC').focus();await page.keyboard.press('Enter');
  assert.equal(await page.locator('[data-guide-province="BC"]').evaluate(node=>node===document.activeElement),true);
  await page.mouse.move(1,1);
  assert.equal(await page.locator('[data-guide-province="BC"]').getAttribute('data-highlighted'),'true');
  assert.equal(await page.locator('.gsm-land.gsm-buyer').evaluate(node=>node.classList.contains('is-focused')),true);
  await stage('Household spending').click();await page.locator('[data-guide-household="AB"]').waitFor();
  assert.equal(await page.locator('.gsm-link').getAttribute('d'),path);
  assert.match(await page.locator('.gsm-endpoints').innerText(),/\/ yr/);
  assert.match(await page.locator('[data-guide-household="AB"]').innerText(),/Annual CPI test error/);
  assert.equal(await page.locator('.gs-guide [class*="eyebrow"]').count(),0);
  checks.push('same map across all stages, exact supported values, failed estimates hidden, keyboard-to-detail focus survives pointer movement');

  for(const width of [390,320]){
    await page.setViewportSize({width,height:844});await stableMap();
    await stage('The exchange').click();await visibleHeading();
    assert.ok(await noOverflow(),`${width}px overflow`);
    const map=await page.locator('.gsm-map').boundingBox();assert.ok(map.height<=255,`compact map ${map.height}px`);
    assert.equal(await page.locator('.gsm-anchor text').first().evaluate(node=>getComputedStyle(node).fontSize),'15px');
    await page.locator('.gs-footer').getByRole('button',{name:'Provincial economy →',exact:true}).click();await visibleHeading();
    await inspect('BC').click();await page.mouse.move(1,1);
    await page.waitForFunction(()=>{const article=document.querySelector('[data-guide-province="BC"]'),map=document.querySelector('.gsm-map').getBoundingClientRect();return article===document.activeElement&&article.dataset.highlighted==='true'&&article.getBoundingClientRect().top>=map.bottom-1;});
    await page.locator('.gs-footer').getByRole('button',{name:'Household spending →',exact:true}).click();await visibleHeading();
    assert.ok(await noOverflow());
  }
  await page.setViewportSize({width:844,height:390});await stableMap();
  assert.equal(await page.locator('.gsm-map').evaluate(node=>getComputedStyle(node).position),'static');
  assert.equal(await page.locator('.gs-map-column').evaluate(node=>getComputedStyle(node).position),'static');
  await inspect('BC').click();await page.mouse.move(1,1);
  assert.equal(await page.locator('[data-guide-household="BC"]').getAttribute('data-highlighted'),'true');
  checks.push('320/390px sticky map preserves readable labels and visible headings; short landscape has normal scrolling');

  await page.route('**/data/provincial-price-response.json',route=>route.abort());
  await page.route('**/data/household-energy-costs.json',route=>route.abort());
  await page.goto(url({guideStep:'provinces'}));await page.reload();
  await page.getByRole('button',{name:'Retry sources',exact:true}).waitFor();
  assert.deepEqual(await page.locator('.gsm-endpoint strong').allTextContents(),['Unavailable','Unavailable']);
  assert.equal(await page.locator('.gsm-endpoint:disabled').count(),2);
  await page.unroute('**/data/provincial-price-response.json');await page.unroute('**/data/household-energy-costs.json');
  await page.getByRole('button',{name:'Retry sources',exact:true}).click();await page.locator('[data-guide-province="BC"]').waitFor();
  assert.equal(await inspect('BC').isEnabled(),true);
  assert.deepEqual(errors,[]);checks.push('source failures show unavailable map values, disable missing targets and recover on retry; zero runtime errors');
  console.log(JSON.stringify({status:'passed',checks,errors}));
}finally{await browser.close();}
