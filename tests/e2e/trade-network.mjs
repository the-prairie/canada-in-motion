import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,...(process.env.TEST_BROWSER_PATH?{executablePath:process.env.TEST_BROWSER_PATH}:{})});
const page=await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'}),errors=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));
await page.route('**/api/analysis/status',route=>route.fulfill({json:{available:false}}));
await page.route('**/api/analysis',()=>{throw Error('No inference expected');});
const base=process.env.TEST_URL||'http://127.0.0.1:4201/';
const url=base+'#v1='+encodeURIComponent(JSON.stringify({view:'economy',economy:{section:'trade',tradeCommodity:'electricity',tradeYear:2024,tradeDisplay:'map',tradeConnection:'AB-BC'}}));
const action=async name=>{const menu=page.locator('.hw-action-menu');if(!await menu.evaluate(e=>e.open))await menu.locator('summary').click();await page.getByRole('button',{name,exact:true}).click();};
try{
  await page.goto(url);await page.locator('.tn-explorer').waitFor();
  assert.match(await page.locator('.tn-inspector').innerText(),/Alberta.*British Columbia/s);
  assert.match(await page.locator('.tn-inspector').innerText(),/60.2M/);
  const maps=page.locator('.tn-map .tn-connection.is-highlighted');
  assert.equal(await maps.count(),1);
  assert.equal(await page.locator('.tn-diagram .tn-connection.is-highlighted').count(),1);
  await page.getByRole('button',{name:'Next trade connection',exact:true}).click();
  const selectedText=await page.locator('.tn-inspector h4').innerText();
  assert.notEqual(selectedText,'Alberta → British Columbia');
  await page.reload();await page.locator('.tn-inspector h4').waitFor();
  assert.equal(await page.locator('.tn-inspector h4').innerText(),selectedText);
  await page.getByLabel('Network province focus',{exact:true}).selectOption('AB');
  const targets=await page.locator('.tn-map .tn-edge-target').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('aria-label')));
  assert.ok(targets.length>0&&targets.every(text=>text.includes('Alberta')));
  await page.reload();assert.equal(await page.getByLabel('Network province focus',{exact:true}).inputValue(),'AB');
  checks.push('linked diagram, exact selected value, next connection, focus and URL reload');
  await page.getByRole('button',{name:'Animate direction',exact:true}).click();
  assert.equal(await page.locator('.tn-direction').first().evaluate(node=>getComputedStyle(node).animationName),'none');
  await page.getByRole('button',{name:'Stop direction',exact:true}).click();
  const target=page.locator('.tn-diagram .tn-edge-target').last();await target.focus();await page.keyboard.press('Enter');
  assert.ok(await target.getAttribute('aria-pressed')==='true');
  const downloadReady=page.waitForEvent('download');await action('Export data');
  const exported=JSON.parse(await readFile(await (await downloadReady).path(),'utf8'));
  assert.equal(exported.selection.tradeFocus,'AB');
  assert.ok(exported.selection.tradeConnection);
  await page.locator('.tn-explorer').screenshot({path:'/tmp/cim-linked-network-desktop.png'});
  await page.getByRole('button',{name:'Clear focus',exact:true}).click();
  assert.equal(await page.getByLabel('Network province focus',{exact:true}).inputValue(),'');
  for(const commodity of ['oil','gas','electricity']){await page.getByLabel('Energy commodity',{exact:true}).selectOption(commodity);await page.locator('.tn-explorer').waitFor();assert.ok(await page.locator('.tn-map .tn-edge-target').count()>0);}
  await page.getByLabel('Trade year',{exact:true}).selectOption('2022');
  assert.match(await page.locator('.tn-inspector').innerText(),/2022/);
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  assert.equal(await page.getByLabel('Trade year',{exact:true}).inputValue(),'2024');
  checks.push('keyboard link selection, reduced motion, clear, commodity/year changes and undo');
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.locator('.tn-explorer').screenshot({path:'/tmp/cim-linked-network-mobile.png'});
  await page.getByRole('button',{name:'Next trade connection',exact:true}).click();
  assert.ok(await page.locator('.tn-inspector h4').isVisible());
  await action('Save investigation');
  await page.getByText('Saved on this device with its original data.',{exact:true}).waitFor();
  await action('Export data');
  await page.reload();await page.locator('.tn-explorer').waitFor();
  assert.ok(await page.getByRole('button',{name:'Map',exact:true}).getAttribute('aria-pressed')==='true');
  assert.deepEqual(errors,[]);
  checks.push('mobile layout, touch-sized steps, save and shared display persistence');
  console.log(JSON.stringify({status:'passed',checks,errors}));
}finally{await browser.close();}
